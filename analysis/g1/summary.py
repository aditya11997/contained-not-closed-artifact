"""Assemble g1_summary.md from the G1 section files (g1_section_*.md) in --out.

    python -m analysis.g1.summary --results results/dev/primary-500 \
        --out results/dev/primary-500/analysis
"""
import argparse
from pathlib import Path

from .common import manifest


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m analysis.g1.summary")
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    out = Path(args.out)
    m = manifest(Path(args.results))
    git = m["git"]
    head = ["# G1 dev exploration — summary (EXPLORATORY, dev seeds only)", "",
            (f"Source run: `{args.results}` ({m['experiment']}, partition {m['partition']}, seeds "
            f"{m['seeds']['first']}–{m['seeds']['last']}, commit {git['commit'][:12]}, dirty {git['dirty']}). "
            "Nothing here is evidence for a pre-registered hypothesis, and no holdout seed was used. Every "
            "number is generated by `analysis/g1/*.py` from result files; sections 4 and 5 use their own "
            "dev runs (named in the section)."), ""]
    sections = sorted(out.glob("g1_section_*.md"))
    body = [p.read_text(encoding="utf-8") for p in sections]
    (out / "g1_summary.md").write_text("\n".join(head) + "\n" + "\n".join(body), encoding="utf-8")
    print(out / "g1_summary.md", [p.name for p in sections])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
