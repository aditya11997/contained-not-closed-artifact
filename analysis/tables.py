"""LaTeX tables and `numbers.tex` macros, so no number in the paper is typed by hand.

Macro names are letters only (LaTeX control words): numbers are spelled out (n = 32 ->
"NThirtyTwo"), policies use short tokens (lm_ack -> "Ack"), e.g. \\FCAckHigh. Every value
comes from analysis.stats over trials.csv; `numbers_tex` sorts macros so the file is stable.
"""
import math

import pandas as pd

from .stats import wilson

POLICY_TOKEN = {"none": "None", "edf": "Edf", "mh": "Mh", "lm_ack": "Ack", "lm_verify": "Verify",
                "lm_reconcile": "Reconcile", "adaptive": "Adaptive", "lm_ack_retry": "AckRetry"}
POLICY_LABEL = {"none": "P0 none", "edf": "P1 EDF", "mh": "P2 MH", "lm_ack": "P3 LM-ack",
                "lm_verify": "P4 LM-verify", "lm_reconcile": "P5 LM-reconcile", "adaptive": "P6 adaptive"}
_ONES = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen", "Seventeen", "Eighteen", "Nineteen"]
_TENS = ["_", "_", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"]


def number_word(n: int) -> str:
    if n < 0 or n >= 10_000:
        raise ValueError(f"no macro word for {n}")
    if n < 20:
        return _ONES[n]
    if n < 100:
        return _TENS[n // 10] + ("" if n % 10 == 0 else _ONES[n % 10])
    if n < 1000:
        return _ONES[n // 100] + "Hundred" + ("" if n % 100 == 0 else number_word(n % 100))
    return number_word(n // 1000) + "Thousand" + ("" if n % 1000 == 0 else number_word(n % 1000))


def token(value) -> str:
    """A letters-only CamelCase token for a factor value or policy."""
    if isinstance(value, bool):
        return "True" if value else "False"
    s = str(value)
    if s in POLICY_TOKEN:
        return POLICY_TOKEN[s]
    if s == "inf":
        return "Inf"
    try:
        f = float(s)
    except ValueError:
        parts = s.replace("-", "_").split("_")
        camel = "".join(part[:1].upper() + part[1:] for part in parts)
        return "".join(number_word(int(ch)) if ch.isdigit() else ch for ch in camel if ch.isalnum())
    if f.is_integer():
        return number_word(int(f))
    whole, frac = s.split(".")
    return number_word(int(whole)) + "Point" + "".join(_ONES[int(ch)] for ch in frac)


def cell_token(row) -> str:
    return f"{token(row['fault'])}{token(row['slack'])}K{token(row['k'])}N{token(row['n'])}"


def macro(name: str, value) -> tuple[str, str]:
    if not name.isalpha():
        raise ValueError(f"macro name {name!r} must be letters only")
    return name, value


def fmt_num(x: float, digits: int = 1) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:,.{digits}f}".replace(",", "{,}")


def fmt_int(x) -> str:
    return f"{int(x):,}".replace(",", "{,}")


def fmt_p(p: float) -> str:
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def fmt_rate(x: float) -> str:
    return f"{100 * x:.2f}\\%"


def numbers_tex(macros: dict[str, str], header: str, source: str = "analysis/report.py") -> str:
    lines = [f"% {header}", f"% Generated by {source} from results files. Do not edit by hand."]
    for name in sorted(macros):
        lines.append(f"\\newcommand{{\\{name}}}{{{macros[name]}}}")
    return "\n".join(lines) + "\n"


def tex_num(x: float, digits: int = 1) -> str:
    """fmt_num for table cells: a negative number gets a math minus ($-$), not a hyphen."""
    s = fmt_num(x, digits)
    return "$-$" + s[1:] if s.startswith("-") else s


def short_policy(policy: str) -> str:
    return POLICY_LABEL[policy].split()[0]


def _tabular(columns: str, header: list[str], body: list[list[str]], caption: str, label: str,
             wide: bool = False, notes: tuple[str, ...] = (), tabcolsep: str = "4pt") -> str:
    """A booktabs float at \\scriptsize with a narrow \\tabcolsep. `wide` makes it a table* (text
    width). `notes` are source comments (definitions kept out of the caption)."""
    env = "table*" if wide else "table"
    out = ["% Generated by analysis/report.py. Do not edit by hand.", *(f"% {n}" for n in notes),
           f"\\begin{{{env}}}[t]", "\\centering", "\\scriptsize", f"\\setlength{{\\tabcolsep}}{{{tabcolsep}}}",
           f"\\caption{{{caption}}}", f"\\label{{{label}}}", f"\\begin{{tabular}}{{{columns}}}", "\\toprule",
           " & ".join(header) + " \\\\", "\\midrule"]
    out += [" & ".join(r) + " \\\\" for r in body]
    out += ["\\bottomrule", "\\end{tabular}", f"\\end{{{env}}}"]
    return "\n".join(out) + "\n"


def _k(k) -> str:
    return "$\\infty$" if str(k) == "inf" else str(k)


def _cell(r) -> str:
    return f"{r.fault}/{r.slack}/{_k(r.k)}/{r.n}"


def _ci(lo, hi) -> str:
    return f"[{tex_num(lo)}, {tex_num(hi)}]"


def contrast_tex(table: pd.DataFrame, caption: str, label: str) -> str:
    """All columns (10 with Holm and Bonferroni); too wide for one column, so a table*."""
    holm = "p_holm" in table
    bonf = "bonf_ci_lo" in table   # post hoc, reporting only (docs/POSTHOC.md PH6)
    header = ["Fault", "Slack", "$k$", "$n$", "Contrast", "Mean $\\Delta$ loss", "95\\% CI",
              *(["Bonferroni CI"] if bonf else []), "Holm $p$" if holm else "$p$", "W/T/L"]
    body = []
    for r in table.itertuples(index=False):
        a, b = r.contrast.split("-")
        body.append([str(r.fault), str(r.slack), _k(r.k), str(r.n), f"{short_policy(a)}$-${short_policy(b)}",
                     tex_num(r.mean_diff), _ci(r.ci_lo, r.ci_hi),
                     *([_ci(r.bonf_ci_lo, r.bonf_ci_hi)] if bonf else []),
                     fmt_p(r.p_holm if holm else r.p), f"{r.a_better}/{r.ties}/{r.a_worse}"])
    return _tabular("llrrlrr" + ("r" if bonf else "") + "rr", header, body, caption, label, wide=True)


def contrast_tex_narrow(table: pd.DataFrame, caption: str, label: str) -> str:
    """The same rows and numbers as `contrast_tex` in 5 columns, for a one-column float: the cell
    factors in one column, mean and 95% CI in one, no Bonferroni CI."""
    holm = "p_holm" in table
    header = ["Cell", "Contrast", "$\\Delta$ loss [95\\% CI]", "Holm $p$" if holm else "$p$", "W/T/L"]
    body = []
    for r in table.itertuples(index=False):
        a, b = r.contrast.split("-")
        body.append([_cell(r), f"{short_policy(a)}$-${short_policy(b)}",
                     f"{tex_num(r.mean_diff)} {_ci(r.ci_lo, r.ci_hi)}",
                     fmt_p(r.p_holm if holm else r.p), f"{r.a_better}/{r.ties}/{r.a_worse}"])
    return _tabular("llrrr", header, body, caption, label, tabcolsep="3pt",
                    notes=("Cell = fault/slack/k/n; W/T/L = seeds where a is better / tied / worse.",))


def contrast_faulty_tex(table: pd.DataFrame, contrasts: tuple[str, ...], faulty: tuple[str, ...], alpha: float,
                        label: str) -> str:
    """Table T4: one row per faulty cell of a Holm-family table; per contrast, the mean and the CI
    at that contrast's Holm level (holm_ci_lo/hi, what decides H2), with a dagger if Holm-rejected."""
    t = table[table["fault"].isin(faulty)]
    header = ["Cell", *(f"{short_policy(c.split('-')[0])}$-${short_policy(c.split('-')[1])} $\\Delta$ [Holm CI]"
                        for c in contrasts)]
    body = []
    for cell_id in t["cell_id"].drop_duplicates():
        rows = t[t["cell_id"] == cell_id].set_index("contrast")
        first = rows.iloc[0]
        line = [f"{first['fault']}/{first['slack']}/{_k(first['k'])}/{first['n']}"]
        for c in contrasts:
            r = rows.loc[c]
            line.append(f"{tex_num(r['mean_diff'])} {_ci(r['holm_ci_lo'], r['holm_ci_hi'])}"
                        + ("$^\\dagger$" if bool(r["holm_reject"]) else ""))
        body.append(line)
    caption = (f"Paired loss differences in the {len(body)} faulty primary cells (fault/slack/$k$/$n$): mean "
               f"and CI at each contrast's Holm level. $^\\dagger$\\,Holm-adjusted $p \\le {alpha:g}$.")
    return _tabular("lrr", header, body, caption, label,
                    notes=(("Holm family: every row of contrasts_primary.csv. The Holm CI is the percentile CI "
                            "at level 1 - alpha/(m - rank + 1) (analysis/stats.py)."),))


def false_closure_tex(fc: pd.DataFrame, caption: str, label: str) -> str:
    """False closures per policy and fault level, summed over the other factors."""
    agg = fc.groupby(["fault", "policy"], sort=False).agg(
        runs=("runs", "sum"), fcs=("false_closures", "sum"), runs_fc=("runs_with_fc", "sum"),
        payments=("payments", "sum")).reset_index()
    header = ["Fault", "Policy", "Runs", "FC", "Runs w/ FC", "FC/payment [95\\% CI]"]
    body = []
    for r in agg.itertuples(index=False):
        lo, hi = wilson(int(r.fcs), int(r.payments))
        body.append([str(r.fault), short_policy(r.policy), fmt_int(r.runs), fmt_int(r.fcs), fmt_int(r.runs_fc),
                     f"{fmt_rate(r.fcs / r.payments)} [{fmt_rate(lo)}, {fmt_rate(hi)}]"])
    return _tabular("llrrrr", header, body, caption, label,
                    notes=("FC = false closures; FC/payment with a Wilson 95% interval.",))
