"""Write paper/macros-generated.tex: an \\input of every generated .tex file that defines macros.

Rules:
- A generated file whose every definition also appears, byte-identical, in another generated file
  is skipped (it is a subset; e.g. stripe.tex is reproduced inside numbers.tex).
- A macro defined in two files with DIFFERENT bodies is an error (exit 1).
- A generated macro that collides with a hand-written one (macros-paper.tex, meta.tex) is an error.
- Repeated definitions inside one file (e.g. \\iffinal ... \\else ... \\fi branches) are fine.
Generated files are never edited.

Usage: python scripts/collect_macros.py [--paper paper]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEF_RE = re.compile(r"\\(?:newcommand|renewcommand|providecommand)\*?\s*\{\\([A-Za-z@]+)\}(\[\d\])?\{(.*)\}\s*$")
NAME_RE = re.compile(r"\\(?:newcommand|renewcommand|providecommand)\*?\s*\{?\\([A-Za-z@]+)")


def definitions(path: Path) -> dict[str, str]:
    """name -> full definition line (single-line definitions, as analysis/report.py writes them)."""
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("%"):
            continue
        m = DEF_RE.match(line)
        if m:
            out.setdefault(m.group(1), line)
        else:
            for name in NAME_RE.findall(line):
                out.setdefault(name, line)
    return out


def collect(paper: Path):
    files = sorted(p for p in (paper / "generated").rglob("*.tex") if definitions(p))
    defs = {p: definitions(p) for p in files}
    # biggest files first, so subsets are skipped rather than their supersets
    order = sorted(files, key=lambda p: (-len(defs[p]), str(p)))
    included, skipped, seen, conflicts = [], [], {}, []
    for p in order:
        mine = defs[p]
        if mine and all(seen.get(n, (None, None))[1] == d for n, d in mine.items()):
            skipped.append(p)
            continue
        for n, d in mine.items():
            if n in seen and seen[n][1] != d:
                conflicts.append(f"\\{n}: {seen[n][0]} vs {p.relative_to(paper)} (different values)")
            elif n in seen:
                conflicts.append(f"\\{n}: defined in {seen[n][0]} and {p.relative_to(paper)} (partial overlap)")
            seen.setdefault(n, (str(p.relative_to(paper)), d))
        included.append(p)
    for hand in ("macros-paper.tex", "meta.tex"):
        hp = paper / hand
        if hp.exists():
            for n in definitions(hp):
                if n in seen:
                    conflicts.append(f"\\{n}: generated ({seen[n][0]}) collides with hand-written {hand}")
    return sorted(included), sorted(skipped), conflicts, len(seen)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--paper", type=Path, default=Path(__file__).resolve().parents[1] / "paper")
    args = ap.parse_args(argv)
    paper = args.paper.resolve()
    included, skipped, conflicts, n_macros = collect(paper)
    if conflicts:
        for c in conflicts:
            print("DUPLICATE", c, file=sys.stderr)
        return 1
    lines = ["% Generated by scripts/collect_macros.py. Do not edit by hand."]
    lines += [f"\\input{{{p.relative_to(paper).with_suffix('').as_posix()}}}" for p in included]
    lines += [f"% skipped (identical subset of another file): {p.relative_to(paper).as_posix()}" for p in skipped]
    (paper / "macros-generated.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"collect_macros: {len(included)} file(s) included, {len(skipped)} identical subset(s) skipped "
          f"({', '.join(p.name for p in skipped) or 'none'}), {n_macros} macros, 0 conflicts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
